"""E8 report: merges results/part_*.json into results.json, writes tables.md and the figures. Called by run.py (stage report)."""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

import run

RES = HERE / "results"
ARMS, SOURCES, JR = run.CFG["arms"], run.CFG["sources"], run.JR
PRIM = run.CFG["primary_arm"]
# Okabe-Ito (colour-blind safe)
COL = {"VISION": "#0072B2", "RAISE": "#E69F00", "OI": "#009E73", "FAKE": "#CC79A7", "real": "#0072B2", "fake": "#D55E00"}


def f3(v):
    return f"{v[0]:.3f} [{v[1]:.3f}, {v[2]:.3f}]"


def load():
    P = {}
    for nm in ("m1", "m2", "m3", "texture"):
        P[nm] = {a: json.loads((RES / f"part_{nm}_{a}.json").read_text()) for a in ARMS}
    P["map"] = json.loads((RES / f"part_map_{PRIM}.json").read_text())
    return P


def tables(P):
    L = ["# E8 (017-embedding-geometry) tables", "",
         "Generated by report.py from results.json. Exploratory (D-016). Readings pre-registered in Amendment 17 (fov512, jpeg75_resize05, block 8). "
         "CIs: 1,000 cluster-bootstrap replicates (devices / caption families / images).", ""]
    for arm in ARMS:
        L += [f"## Arm `{arm}` ({'primary' if arm == PRIM else 'reported'})", ""]
        # ---- M1
        m1 = P["m1"][arm]
        L += ["### M1: C2ST AUROC (group-held-out), real-real vs real-vs-fake", "",
              "| feat | cond | mode | VISION-RAISE | VISION-OI | RAISE-OI | VISION-FAKE | RAISE-FAKE | OI-FAKE | mean real-real | mean real-fake | ratio rr/rf [CI] | R1 entangled (ratio >= 0.9) |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for k, v in m1.items():
            feat, cond, mode = k.split("|")
            p = v["pairs"]
            L.append(f"| {feat} | {cond} | {mode} | " + " | ".join(f"{p[q][0]:.3f}" for q in ["VISION-RAISE", "VISION-OI", "RAISE-OI", "VISION-FAKE", "RAISE-FAKE", "OI-FAKE"])
                     + f" | {f3(v['real_real_mean'])} | {f3(v['real_fake_mean'])} | {f3(v['ratio'])} | {v['R1_entangled']} |")
        L.append("")
        # ---- M2
        m2 = P["m2"][arm]
        L += [f"### M2: directions (twin pairs {m2['n_twin_pairs']} over {m2['n_twin_reals']} RAISE train reals / {m2['n_twin_families']} caption families)", ""]
        for feat, fo in m2["feats"].items():
            nm = fo["names"]
            for key, title in (("cos_matrix_pooled_z", "pooled-z space (headline)"), ("cos_matrix_raw", "raw space (sensitivity)")):
                L += [f"**{feat}, cosines, {title}**", "", "| | " + " | ".join(nm) + " |", "|---|" + "---|" * len(nm)]
                for i, a in enumerate(nm):
                    L.append(f"| {a} | " + " | ".join(f"{fo[key][i][j]:.3f}" for j in range(len(nm))) + " |")
                L.append("")
            if "split_half" in fo:
                L += ["Split-half noise reference (probe-normal cosine between two random half-group fits of the same source): " +
                      ", ".join(f"{S} {v['mean']:.3f} (min {v['min']:.3f})" for S, v in fo["split_half"].items()), ""]
            L += ["d_twin variants, cosine with d_probe(S) (pooled-z): " + "; ".join(
                f"{vn}: " + ", ".join(f"{S} {x:.3f}" for S, x in d.items()) for vn, d in fo["twin_variants_cos"].items()), ""]
            L += [f"**{feat}: d_twin projection alone (T-aug direction, no LOGO leakage: direction estimated without the held-out generator), macro AUROC over 8 generators; FPR at the 1% threshold of RAISE calib reals**", "",
                  "| held-out reals | cond | AUROC [CI] | FPR reading A (k/n) [CP95] | FPR reading B |", "|---|---|---|---|---|"]
            for S in SOURCES:
                for c in run.EVAL:
                    a, b = fo["twin_eval"][S]["A"][c], fo["twin_eval"][S]["B"][c]
                    L.append(f"| {S}{' (in-source reference)' if S == 'RAISE' else ''} | {c} | {f3(a['auroc'])} | {a['fpr']:.3f} ({a['k']}/{a['n']}) [{a['cp95'][0]:.3f}, {a['cp95'][1]:.3f}] | {b['fpr']:.3f} |")
            L += ["", f"**{feat}: R2 with drop-one-generator** (min pairwise cosine of d_probe(S); d_twin AUROC on VISION / OI; R2 = min cos >= 0.5 and both AUROC >= 0.80)", "",
                  "| subset | min cos | d_twin AUROC VISION | d_twin AUROC OI | R2 holds |", "|---|---|---|---|---|"]
            for sn, r in fo["robust"].items():
                L.append(f"| {sn} | {r['min_cos']:.3f} | {r['twin_auroc']['VISION']:.3f} | {r['twin_auroc']['OI']:.3f} | {r['R2']} |")
            L.append("")
        # ---- M3
        m3 = P["m3"][arm]
        L += ["### M3: source-subspace removal, F_b8, retrained E7 probe, training on the two other sources", "",
              "| held-out | variant (k = removed dims) | AUROC [CI] | FPR reading A (k/n) [CP95] | FPR reading B | calib source-ID AUROC | chosen |", "|---|---|---|---|---|---|---|"]
        for S in SOURCES:
            so = m3["sources"][S]
            for vn, v in so["variants"].items():
                a, b = v["A"][JR], v["B"][JR]
                kk = 0 if vn == "e7" else int(vn.split("=")[1])
                sid = so["calib_source_id_auc"].get(str(kk), "")
                sid = f"{sid:.3f}" if sid != "" else ""
                L.append(f"| {S} | {vn} | {f3(a['auroc'])} | {a['fpr']:.3f} ({a['k']}/{a['n']}) [{a['cp95'][0]:.3f}, {a['cp95'][1]:.3f}] | {b['fpr']:.3f} | {sid} | {'<--' if vn == 'k=' + str(so['chosen_k']) else ''} |")
        L += ["", "Chosen-k AUROC change vs E7 (paired bootstrap): " + "; ".join(f"{S} {d['delta']:+.3f} [{d['ci_lo']:+.3f}, {d['ci_hi']:+.3f}]" for S, d in m3["chosen_delta_auroc"].items()), ""]
        L += ["**R3 / kill labels** (chosen k per source; reading A, B; drop-one-generator)", "", "| subset | label A | label B | min AUROC (A) | max FPR (A) | improved sources (A) |", "|---|---|---|---|---|---|"]
        for sn in m3["robust"]["A"]:
            a, b = m3["robust"]["A"][sn], m3["robust"]["B"][sn]
            L.append(f"| {sn} | {a['label']} | {b['label']} | {min(v['auc'] for v in a['per'].values()):.3f} | {max(v['fpr'] for v in a['per'].values()):.3f} | "
                     + ", ".join(S for S, x in a["improved"].items() if x) + " |")
        L += ["", "Uniform-j sensitivity (same number of extra PCs for every source, all generators):", "", "| j | label A | label B |", "|---|---|---|"]
        for jn in m3["uniform_j"]["A"]:
            L.append(f"| {jn} | {m3['uniform_j']['A'][jn]['label']} | {m3['uniform_j']['B'][jn]['label']} |")
        L.append("")
        # ---- texture
        tx = P["texture"][arm]
        L += ["### Laplacian texture baseline (macro AUROC, fake-higher sign chosen on training-source calib vs train fakes; gate: < 0.70 laundered)", "",
              "| held-out | cond | chosen sign | chosen AUROC [CI] | best sign |", "|---|---|---|---|---|"]
        for S in SOURCES:
            for c in run.EVAL:
                t = tx[S][c]
                L.append(f"| {S} | {c} | {t['sign']:+.0f} | {f3(t['chosen'])} | {max(t['fake_higher'][0], t['fake_lower'][0]):.3f} |")
        L.append("")
    (RES / "tables.md").write_text("\n".join(L))


# ---------------------------------------------------------------------------- figures
def style():
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "axes.grid": True, "grid.alpha": 0.25,
                         "figure.dpi": 130, "savefig.bbox": "tight"})


def fig_map(P, key, fname, title):
    M = P["map"]
    cat, lab = np.array(M["cat"]), np.array(M["label"])
    fig, ax = plt.subplots(2, 2, figsize=(10, 8.4))
    for ci, c in enumerate(run.EVAL):
        xy = np.array(M[key][c])
        idx = np.arange(len(cat)) if key == "pca" else np.array(M["tsne_idx"])
        xy_, cat_, lab_ = (xy, cat[idx], lab[idx])
        a = ax[0, ci]
        for s in ["FAKE"] + SOURCES:
            m = cat_ == s
            a.scatter(xy_[m, 0], xy_[m, 1], s=7, alpha=0.55 if s != "FAKE" else 0.35, c=COL[s], marker="x" if s == "FAKE" else "o",
                      linewidths=0.6, label=f"{s} (n={m.sum()})" if s != "FAKE" else f"fakes, 8 gens (n={m.sum()})")
        a.set_title(f"{c}: coloured by source")
        a = ax[1, ci]
        for nm, v in (("real", 0), ("fake", 1)):
            m = lab_ == v
            a.scatter(xy_[m, 0], xy_[m, 1], s=7, alpha=0.5, c=COL[nm], marker="o" if v == 0 else "x", linewidths=0.6, label=f"{nm} (n={m.sum()})")
        a.set_title(f"{c}: real vs fake")
        for r in (0, 1):
            ax[r, ci].set_xlabel("PC1" if key == "pca" else "t-SNE 1")
            ax[r, ci].set_ylabel("PC2" if key == "pca" else "t-SNE 2")
    ax[0, 0].legend(markerscale=2, fontsize=7, loc="best")
    ax[1, 0].legend(markerscale=2, fontsize=7, loc="best")
    sub = f"PC1/PC2 explain {M['pca_var'][0]:.1%} / {M['pca_var'][1]:.1%} of variance" if key == "pca" else "t-SNE of 50 PCs, perplexity 30, subsample"
    fig.suptitle(f"{title} (DINOv2 block 8, fov512; {sub}; descriptive)", y=1.0)
    fig.tight_layout()
    fig.savefig(RES / fname)
    plt.close(fig)


def fig_m1m2(P):
    m1, m2 = P["m1"][PRIM], P["m2"][PRIM]
    fig, ax = plt.subplots(1, 3, figsize=(15, 4.4), gridspec_kw={"width_ratios": [1.5, 1.1, 1.1]})
    a = ax[0]
    v = m1[f"F_b8|{JR}|full"]
    vc = m1[f"F_b8|clean|full"]
    names = ["VISION-RAISE", "VISION-OI", "RAISE-OI", "VISION-FAKE", "RAISE-FAKE", "OI-FAKE"]
    x = np.arange(6)
    for off, (vv, lab_) in zip((-0.2, 0.2), ((vc, "clean"), (v, JR))):
        y = [vv["pairs"][n][0] for n in names]
        lo = [vv["pairs"][n][0] - vv["pairs"][n][1] for n in names]
        hi = [vv["pairs"][n][2] - vv["pairs"][n][0] for n in names]
        cols = [COL["VISION"] if i < 3 else COL["fake"] for i in range(6)]
        a.bar(x + off, y, 0.38, yerr=[lo, hi], color=cols, alpha=0.5 if lab_ == "clean" else 0.95, capsize=2, label=lab_, edgecolor="white")
    a.axhline(0.5, c="k", lw=0.6)
    a.set_xticks(x)
    a.set_xticklabels(names, rotation=30, ha="right")
    a.set_ylim(0.4, 1.02)
    a.set_ylabel("group-held-out C2ST AUROC")
    r = v["ratio"]
    a.set_title(f"M1 (F_b8): real-real (blue) vs real-fake (orange)\nlight = clean, dark = {JR}\nmean ratio at {JR}: {r[0]:.2f} [{r[1]:.2f}, {r[2]:.2f}]; R1 threshold 0.9", fontsize=9)
    a = ax[1]
    fo = m2["feats"]["F_b8"]
    nm = ["probe:VISION", "probe:RAISE", "probe:OI", "twin"]
    Mx = np.array(fo["cos_matrix_pooled_z"])
    im = a.imshow(Mx, vmin=-1, vmax=1, cmap="RdBu_r")
    a.set_xticks(range(4))
    a.set_yticks(range(4))
    a.set_xticklabels(["d_probe\nVISION", "d_probe\nRAISE", "d_probe\nOI", "d_twin"], fontsize=8)
    a.set_yticklabels(["d_probe VISION", "d_probe RAISE", "d_probe OI", "d_twin"], fontsize=8)
    for i in range(4):
        for j in range(4):
            a.text(j, i, f"{Mx[i, j]:.2f}", ha="center", va="center", fontsize=9, color="white" if abs(Mx[i, j]) > 0.6 else "black")
    a.grid(False)
    a.set_title("M2 (F_b8): cosines of directions\n(pooled-z space)", fontsize=9)
    fig.colorbar(im, ax=a, fraction=0.046)
    a = ax[2]
    for si, S in enumerate(SOURCES):
        for ci, c in enumerate(run.EVAL):
            e = fo["twin_eval"][S]["A"][c]["auroc"]
            a.errorbar(si + (ci - 0.5) * 0.22, e[0], yerr=[[e[0] - e[1]], [e[2] - e[0]]], fmt="o" if ci else "s", c=COL[S], capsize=3, label=c if si == 0 else None)
    a.axhline(0.8, c="k", ls="--", lw=0.8)
    a.text(2.45, 0.805, "R2: 0.80", ha="right", fontsize=8)
    a.set_xticks(range(3))
    a.set_xticklabels(["VISION", "RAISE\n(in-source)", "OI"])
    a.set_ylim(0.4, 1.0)
    a.set_ylabel("macro AUROC, d_twin projection alone")
    a.legend(fontsize=8, loc="lower left")
    a.set_title("M2: AUROC of the twin direction alone\n(8 generators, direction estimated without the held-out one)", fontsize=9)
    fig.tight_layout()
    fig.savefig(RES / "fig3_m1_m2.png")
    plt.close(fig)


def fig_m3(P):
    fig, ax = plt.subplots(2, 3, figsize=(12.5, 6.4), sharex="col")
    for arm, ls in ((PRIM, "-"), ("orig", ":")):
        m3 = P["m3"][arm]
        for ci, S in enumerate(SOURCES):
            so = m3["sources"][S]
            ks = sorted([int(k.split("=")[1]) for k in so["variants"] if k != "e7"])
            auc = [so["variants"][f"k={k}"]["A"][JR]["auroc"] for k in ks]
            fpr = [so["variants"][f"k={k}"]["A"][JR]["fpr"] for k in ks]
            e7a, e7f = so["variants"]["e7"]["A"][JR]["auroc"], so["variants"]["e7"]["A"][JR]["fpr"]
            a = ax[0, ci]
            a.errorbar(ks, [x[0] for x in auc], yerr=[[x[0] - x[1] for x in auc], [x[2] - x[0] for x in auc]], c=COL[S], ls=ls, marker="o", capsize=2,
                       label=f"{arm}: E8 (k removed dims)")
            a.axhline(e7a[0], c="gray", ls=ls, lw=1.2, label=f"{arm}: E7 (no removal)")
            a.plot([so["chosen_k"]], [so["variants"][f"k={so['chosen_k']}"]["A"][JR]["auroc"][0]], marker="*", ms=14, c="k", ls="none", zorder=5,
                   label="chosen k" if arm == PRIM else None)
            a = ax[1, ci]
            a.plot(ks, fpr, c=COL[S], ls=ls, marker="o")
            a.axhline(e7f, c="gray", ls=ls, lw=1.2)
            a.plot([so["chosen_k"]], [so["variants"][f"k={so['chosen_k']}"]["A"][JR]["fpr"]], marker="*", ms=14, c="k", ls="none", zorder=5)
    for ci, S in enumerate(SOURCES):
        ax[0, ci].axhline(0.85, c="k", lw=0.7, ls="--")
        ax[1, ci].axhline(0.05, c="k", lw=0.7, ls="--")
        ax[0, ci].set_title(f"held-out {S}")
        ax[1, ci].set_xlabel("removed source-subspace dimensions k")
        ax[0, ci].set_ylim(0.5, 1.0)
        ax[1, ci].set_ylim(0, 0.5)
    ax[0, 0].set_ylabel(f"macro AUROC at {JR}\n(dashed black: 0.85)")
    ax[1, 0].set_ylabel("FPR at transferred 1% threshold\n(dashed black: 5%)")
    ax[0, 0].legend(fontsize=7, loc="lower left")
    fig.suptitle("M3: source-subspace removal, F_b8 (solid = fov512 primary, dotted = orig)", y=1.0)
    fig.tight_layout()
    fig.savefig(RES / "fig4_m3.png")
    plt.close(fig)


def main():
    style()
    P = load()
    meta = dict(config=run.CFG)
    (RES / "results.json").write_text(json.dumps(dict(meta=meta, **{k: P[k] for k in ("m1", "m2", "m3", "texture")},
                                                      map={k: v for k, v in P["map"].items() if k in ("pca_var", "eta2_source_among_reals_pc1_pc2")}), indent=1, default=float))
    tables(P)
    fig_map(P, "pca", "fig1_map_pca.png", "2-D map (PCA)")
    fig_map(P, "tsne", "fig2_map_tsne.png", "2-D map (t-SNE)")
    fig_m1m2(P)
    fig_m3(P)
    run.log("report written")


if __name__ == "__main__":
    main()
