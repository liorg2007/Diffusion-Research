"""results.json -> results/tables.md (called by run.py report)."""
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent


def f3(c):
    if c is None:
        return "-"
    if isinstance(c, (list, tuple)) and len(c) == 3:
        return f"{c[0]:.3f} [{c[1]:.3f}, {c[2]:.3f}]"
    return f"{c:.3f}"


def mat(names, M, short=None):
    sh = short or [n[:9] for n in names]
    L = ["| true \\ pred | " + " | ".join(sh) + " |", "|---|" + "---|" * len(names)]
    for i, n in enumerate(names):
        L.append(f"| {sh[i]} | " + " | ".join(str(int(x)) for x in M[i]) + " |")
    return "\n".join(L)


def write_tables(R, A):
    L = []
    w = L.append
    lab = R["labels"]
    w("# E11 (020-attr-foundation) tables\n")
    w("Generated by run.py report from results.json. Frozen pre-registration: docs/08 + docs/09. 1,000 cluster-bootstrap replicates (clusters: caption family / id / device / image / group). "
      "Point [95% CI]. Primary condition: jpeg75_resize05 (RAID: jpeg(75)). Training regimes: T-mix (clean + primary + social_sim) and clean-train. Chance levels are in every table.\n")
    w("## Labels\n")
    h1, ou, h4 = lab["H-A1"], lab["open_set_usable"], lab["H-A4"]
    w(f"- **H-A1: {h1['label']}** {h1.get('parts', '')} values: bacc {f3(h1['values']['bacc'])}, M1 bacc {h1['values']['m1_bacc']:.3f}, pairwise (macro over generator pairs) {h1['values']['pairwise']:.3f}, RAID 4-way bacc {h1['values']['raid_bacc']:.3f}")
    w(f"- **open-set usable: {ou['usable_either']}** (-max softmax: mean {ou['msp']['mean']:.3f}, min {ou['msp']['min']:.3f}, usable {ou['msp']['usable']}; Mahalanobis: mean {ou['maha']['mean']:.3f}, min {ou['maha']['min']:.3f}, usable {ou['maha']['usable']})")
    w(f"- **H-A4: {h4['label']}** mean novelty AUROC {h4.get('mean', float('nan')):.3f}, min {h4.get('min', float('nan')):.3f}; **DISCOVERY: {lab['DISCOVERY']}** (min kind accuracy over the 8 real sources {h4.get('min_kind_real', float('nan')):.3f})")
    w(f"- all validity gates ok: {lab['all_gates_ok']}\n")

    w("## Validity gates (docs/08 section 3)\n")
    w("| gate | ok | detail |\n|---|---|---|")
    for k, g in R["gates"].items():
        det = {kk: vv for kk, vv in g.items() if kk not in ("ok", "note", "by_cond")}
        if "by_cond" in g:
            det["by_cond"] = {c: round(v, 3) for c, v in g["by_cond"].items()}
        w(f"| {k} | {'PASS' if g['ok'] else '**FAIL**'} | {str(det)[:300]} {g.get('note', '')} |")
    w("")

    for an in ("ha1_main", "ha1_raid"):
        a = R["analyses"][an]
        pc = a["primary"]
        K = len(a["classes"])
        title = "H-A1 main: 8 generators (Synthbuster 6 + sd3 + flux), fov512" if an == "ha1_main" else "H-A1 replication: RAID 4-way (existing 100 ids), fov224, JPEG-only conditions"
        w(f"## {title}\n")
        w(f"n = {a['n']} images, {a['n_clusters']} clusters; chance bacc = {1 / K:.3f}; majority-class rate = {a['fs']['tmix|nested']['summary'][pc]['majority_rate']:.3f}; primary = {pc}\n")
        has_pw = "pw" in a["fs"]["tmix|nested"]["summary"][pc]
        for regime, nm in (("tmix", "T-mix training"), ("clean", "clean-train transfer")):
            w(f"### Feature sets at {pc}, {nm}\n")
            w("| method | bacc | macro-F1 | " + ("bacc w/o firefly | " if a["drop_macro"] else "") + ("pairwise macro | pairwise pooled | strict(both) macro | " if has_pw else "") + "chosen C / feature set per fold |")
            w("|---|---|---|" + ("---|" if a["drop_macro"] else "") + ("---|---|---|" if has_pw else "") + "---|")
            for fs in ("b4", "b8", "b12", "cat", "nested", "M1", "M1gbm"):
                e = a["fs"][f"{regime}|{fs}"]
                s = e["summary"][pc]
                ch = e.get("chosen_fs") or {f: (c[0] if c[0] is None else f"{c[0]:g}") for f, c in e.get("chosen", {}).items()}
                row = f"| {fs if fs not in ('M1', 'M1gbm') else fs + ' (baseline)'} | {f3(s['bacc'])} | {f3(s['mf1'])} | "
                if a["drop_macro"]:
                    row += f"{f3(s['bacc_drop'])} | "
                if has_pw:
                    row += f"{f3(s['pw']['macro'])} | {f3(s['pw']['pooled'])} | {f3(s['pw_strict']['macro'])} | "
                row += f"{ch} |"
                w(row)
            m0 = a["M0_raw"]
            w(f"| M0 raw-file metadata (baseline, no condition) | {f3(m0['bacc'])} | {f3(m0['mf1'])} | " + (f"{f3(m0.get('bacc_drop'))} | " if a["drop_macro"] else "") + ("- | - | - | " if has_pw else "") + f"RF; {m0['n_ext_mismatch']} files whose extension differs from the content |")
            w("")
        w(f"M0 on PREPROCESSED tensors (must be at chance {1 / K:.3f}): " + ", ".join(f"{c} {v:.3f}" for c, v in a["M0_tensor"].items()) + "\n")
        hl = a["holm_vs_M1_plus_010"]
        w("Holm across the 4 feature sets, H0: bacc - M1 <= 0.10 (T-mix, primary): " + "; ".join(f"{f} p={p:.4f} (Holm {ph:.4f})" for f, p, ph in zip(hl["fs"], hl["p"], hl["p_holm"])) + "\n")
        nm1 = a["nested_minus_M1"]
        w(f"nested - M1 bacc (paired): {nm1['delta']:+.3f} [{nm1['ci_lo']:+.3f}, {nm1['ci_hi']:+.3f}]\n")
        if "layer_contrast_b8_minus_b12" in a:
            lc, lc2 = a["layer_contrast_b8_minus_b12"], a["layer_contrast_b8_minus_b12_clean_train"]
            w(f"Layer contrast b8 - b12 bacc at {pc}: T-mix {lc['delta']:+.3f} [{lc['ci_lo']:+.3f}, {lc['ci_hi']:+.3f}]; clean-train {lc2['delta']:+.3f} [{lc2['ci_lo']:+.3f}, {lc2['ci_hi']:+.3f}]\n")
        w("### bacc per condition (all five/three conditions; screenshot_sim and mavali_medium are never seen in training)\n")
        conds = list(a["fs"]["tmix|nested"]["summary"].keys())
        w("| method / regime | " + " | ".join(conds) + " |\n|---|" + "---|" * len(conds))
        for regime in ("tmix", "clean"):
            for fs in ("b4", "b8", "b12", "cat", "nested", "M1"):
                s = a["fs"][f"{regime}|{fs}"]["summary"]
                w(f"| {fs} / {regime} | " + " | ".join(f3(s[c]["bacc"]) for c in conds) + " |")
        w(f"| M0 raw metadata | " + " | ".join(f3(a["M0_raw"]["bacc"]) for _ in conds) + " |")
        w(f"\nchance {1 / K:.3f}\n")
        if has_pw:
            w("### pairwise (macro over generator pairs) per condition, nested\n")
            w("| regime | " + " | ".join(conds) + " |\n|---|" + "---|" * len(conds))
            for regime in ("tmix", "clean"):
                s = a["fs"][f"{regime}|nested"]["summary"]
                w(f"| {regime} | " + " | ".join(f3(s[c]["pw"]["macro"]) for c in conds) + " |")
            w("\nchance 0.5\n")
        w("### per-generator recall, nested (T-mix | clean-train), primary / clean\n")
        w("| generator | T-mix " + pc + " | T-mix clean | clean-train " + pc + " | clean-train clean | M1 T-mix " + pc + " | M0 raw |\n|---|---|---|---|---|---|---|")
        for g in a["classes"]:
            w(f"| {g} | {a['fs']['tmix|nested']['summary'][pc]['recall'][g]:.3f} | {a['fs']['tmix|nested']['summary']['clean']['recall'][g]:.3f} | "
              f"{a['fs']['clean|nested']['summary'][pc]['recall'][g]:.3f} | {a['fs']['clean|nested']['summary']['clean']['recall'][g]:.3f} | "
              f"{a['fs']['tmix|M1']['summary'][pc]['recall'][g]:.3f} | {a['M0_raw']['recall'][g]:.3f} |")
        w(f"\n### confusion matrix, nested, T-mix, {pc} (rows = truth)\n")
        w(mat(a["classes"], np.array(a["fs"]["tmix|nested"]["summary"][pc]["confusion"])))
        w("\n### confusion matrix, nested, clean-train, " + pc + "\n")
        w(mat(a["classes"], np.array(a["fs"]["clean|nested"]["summary"][pc]["confusion"])))
        w("\n### confusion matrix M0 raw metadata\n")
        w(mat(a["classes"], np.array(a["M0_raw"]["confusion"])))
        w("\n### confusion matrix M1 (T-mix, " + pc + ")\n")
        w(mat(a["classes"], np.array(a["fs"]["tmix|M1"]["summary"][pc]["confusion"])))
        if has_pw:
            w("\n### same-caption pairwise accuracy per generator pair (nested, T-mix, " + pc + "; chance 0.5; content is identical within a pair)\n")
            pm = a["fs"]["tmix|nested"]["summary"][pc]["pair_matrix"]
            w("| pair | accuracy |\n|---|---|")
            for k_, v_ in sorted(pm.items(), key=lambda kv: kv[1]):
                w(f"| {k_} | {v_:.3f} |")
        w("")
        if "logo" in a:
            w(f"### Open set: leave-one-generator-out AUROC (held-out generator vs known-generator test images), {pc}, nested feature set\n")
            for regime in ("tmix", "clean"):
                lg = a["logo"][f"{regime}|nested"]
                w(f"**{regime}**\n")
                w("| held-out generator | -max softmax AUROC | Mahalanobis AUROC |\n|---|---|---|")
                for g in a["classes"]:
                    w(f"| {g} | {f3(lg['msp'][pc][g])} | {f3(lg['maha'][pc][g])} |")
                for sc in ("msp", "maha"):
                    v = [lg[sc][pc][g][0] for g in a["classes"]]
                    vn = [lg[sc][pc][g][0] for g in a["classes"] if g != a["drop_macro"]]
                    w(f"- {sc}: mean {np.mean(v):.3f}, min {min(v):.3f}; without firefly held out: mean {np.mean(vn):.3f}, min {min(vn):.3f}")
                w("")
            w("mean LOGO AUROC per condition and feature set (T-mix / clean-train; msp | maha); chance 0.5\n")
            conds = list(a["logo"]["tmix|nested"]["msp"].keys())
            w("| feature set / regime | " + " | ".join(conds) + " |\n|---|" + "---|" * len(conds))
            for regime in ("tmix", "clean"):
                for fk in ("b4", "b8", "b12", "cat", "nested"):
                    lg = a["logo"][f"{regime}|{fk}"]
                    w(f"| {fk} / {regime} | " + " | ".join(f"{np.mean([lg['msp'][c][g][0] for g in a['classes']]):.3f} \\| {np.mean([lg['maha'][c][g][0] for g in a['classes']]):.3f}" for c in conds) + " |")
            w("")

    h4 = R["ha4"]
    names = h4["classes"]
    w("## H-A4: unified 16-source space (DINOv2 features, fov512), leave-one-source-out\n")
    w(f"n = {h4['n']} images, {h4['n_clusters']} clusters; novelty chance AUROC 0.5; closed-set chance bacc {1 / 16:.4f}. Cross-fitted: each image is scored by models that never saw its group. "
      "Novelty = Mahalanobis (shared Ledoit-Wolf covariance); kind accuracy = the nearest known source (Mahalanobis) is of the same kind (real/fake).\n")
    pc = "jpeg75_resize05"
    for regime in ("tmix", "clean"):
        w(f"### Novelty AUROC and kind accuracy per held-out source, b8, {regime}, {pc}\n")
        e = h4["fs"][f"{regime}|b8"]["per_cond"][pc]
        refm = {"RAISE": "RAISE", "OI": "OI", "UNS": "UNS", "WMC": "WMC", "HDRP": "HDRP"}
        w("| held-out source | kind | novelty AUROC [CI] | kind accuracy [CI] | kNN-10 AUROC | kNN-10 kind acc | most frequent nearest known sources | E10 k=5 FPR (019, F_b8) |\n|---|---|---|---|---|---|---|---|")
        kinds = {n: k for n, k in zip(h4["holdouts"], [s for s in ["fake"] * 8 + ["real"] * 9])}
        for n in h4["holdouts"]:
            x = e[n]
            ref = h4["e10_reference_k5_b8"].get(refm.get(n, ""), {})
            w(f"| {n} | {kinds[n]} | {f3(x['auroc'])} | {f3(x['kind_acc'])} | {f3(x.get('knn_auroc'))} | {x.get('knn_kind_acc', float('nan')):.3f} | {x['nearest_source']} | {ref.get('fpr', '-')} |")
        w("")
    w("### Summary over the 16 single held-out sources (VISION-all is a separate descriptive row above)\n")
    w("| feature set / regime | " + " | ".join(h4["fs"]["tmix|b8"]["summary"].keys()) + " |\n|---|" + "---|" * len(h4["fs"]["tmix|b8"]["summary"]))
    for key, ent in h4["fs"].items():
        w(f"| {key.split('|')[1]} / {key.split('|')[0]}: mean AUROC | " + " | ".join(f3(ent["summary"][c]["mean"]) for c in ent["summary"]) + " |")
        w(f"| {key.split('|')[1]} / {key.split('|')[0]}: mean w/o firefly | " + " | ".join(f3(ent["summary"][c]["mean_nofirefly"]) for c in ent["summary"]) + " |")
        w(f"| {key.split('|')[1]} / {key.split('|')[0]}: min (argmin) | " + " | ".join(f"{ent['summary'][c]['min']:.3f} ({ent['summary'][c]['argmin']})" for c in ent["summary"]) + " |")
    hh = h4["holm_mean_auroc_gt_085"]
    w("\nHolm over b4/b8/b12, H0: mean AUROC <= 0.85 (T-mix, primary): " + "; ".join(f"{f} p={p:.4f} (Holm {ph:.4f})" for f, p, ph in zip(hh["fs"], hh["p"], hh["p_holm"])) + "\n")
    w("### Per-source AUROC at every condition (b8, T-mix)\n")
    conds = list(h4["fs"]["tmix|b8"]["per_cond"].keys())
    w("| held-out | " + " | ".join(conds) + " |\n|---|" + "---|" * len(conds))
    for n in h4["holdouts"]:
        w(f"| {n} | " + " | ".join(f3(h4["fs"]["tmix|b8"]["per_cond"][c][n]["auroc"]) for c in conds) + " |")
    w("\n### Baselines for H-A4 (closed-set 16-way bacc; chance 0.0625)\n")
    w("| method | " + " | ".join(conds) + " |\n|---|" + "---|" * len(conds))
    for key in h4["fs"]:
        if key.split("|")[1] in ("b8", "M1", "b4", "b12"):
            w(f"| {key.split('|')[1]} LR / {key.split('|')[0]} | " + " | ".join(f3(h4["fs"][key]["closed"][c]["bacc"]) for c in conds) + " |")
    w(f"| M0 raw metadata (HDR+ without q-table: {h4['M0_raw_16way']['n_hdrp_no_qtable']} rows) | {f3(h4['M0_raw_16way']['bacc'])} (all conditions) |")
    w("\nM1 (12 texture statistics) novelty AUROC mean over the 16 sources, T-mix: " + ", ".join(f"{c} {f3(h4['fs']['tmix|M1']['summary'][c]['mean'])}" for c in conds) + "\n")
    w("M0 on PREPROCESSED tensors (must be at chance 0.0625): " + ", ".join(f"{c} {v:.3f}" for c, v in h4["M0_tensor"].items()) + "\n")
    w("### Closed-set 16-way confusion, b8 LR, T-mix, " + pc + "\n")
    w(mat(names, np.array(h4["fs"]["tmix|b8"]["closed"][pc]["confusion"]), [n[:6] for n in names]))
    w("\nper-source recall (b8 T-mix | b8 clean-train | M1 T-mix), " + pc + ": " + "; ".join(
        f"{n} {h4['fs']['tmix|b8']['closed'][pc]['recall'][n]:.2f}|{h4['fs']['clean|b8']['closed'][pc]['recall'][n]:.2f}|{h4['fs']['tmix|M1']['closed'][pc]['recall'][n]:.2f}" for n in names))
    w(f"\nkind accuracy of the closed-set head (b8 T-mix, {pc}): {h4['fs']['tmix|b8']['closed'][pc]['kind_acc']:.3f}\n")
    (HERE / "results" / "tables.md").write_text("\n".join(L) + "\n")
